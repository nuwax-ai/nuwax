import { build } from 'esbuild';
import { promises as fs } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rendererVersion = '1.0.7';
const zipVersion = '3.10.1';
const outputPath = path.join(
  root,
  'public/static/file-preview/file-preview-pptx.js',
);

/** 只打包已钉版本并应用实例资源清理补丁的 main，禁止落回其他浏览器入口。 */
export async function buildFilePreviewPptx() {
  const [project, renderer, zip] = await Promise.all([
    fs.readFile(path.join(root, 'package.json'), 'utf8').then(JSON.parse),
    fs
      .readFile(require.resolve('pptx-preview/package.json'), 'utf8')
      .then(JSON.parse),
    fs.readFile(require.resolve('jszip/package.json'), 'utf8').then(JSON.parse),
  ]);
  if (
    project.dependencies['pptx-preview'] !== rendererVersion ||
    renderer.version !== rendererVersion ||
    project.dependencies.jszip !== zipVersion ||
    zip.version !== zipVersion
  ) {
    throw new Error(
      `静态 PPTX 预览必须使用 pptx-preview@${rendererVersion} 和 jszip@${zipVersion}，升级后需重新审查补丁并生成资产。`,
    );
  }
  const rendererEntry = require.resolve('pptx-preview');
  const packageRoot = path.dirname(
    require.resolve('pptx-preview/package.json'),
  );
  if (rendererEntry !== path.resolve(packageRoot, renderer.main)) {
    throw new Error('静态 PPTX 预览必须使用 pptx-preview 的 package.main。');
  }
  const ownerEntry = path.join(path.dirname(rendererEntry), 'preview-owner.js');
  const [rendererSource, ownerSource] = await Promise.all([
    fs.readFile(rendererEntry, 'utf8'),
    fs.readFile(ownerEntry, 'utf8'),
  ]);
  if (
    !rendererSource.includes('from "./preview-owner.js"') ||
    !rendererSource.includes('nuwaxScheduleChart') ||
    !rendererSource.includes('nuwaxAssertCurrentPreview') ||
    !ownerSource.includes('element.isConnected')
  ) {
    throw new Error(
      'pptx-preview 实例资源清理补丁未生效，请先按 lockfile 安装依赖。',
    );
  }
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/utils/filePreviewPptxEntry.ts'],
    // esbuild 的 browser/module 优先级不得绕过已经打补丁的 package.main。
    alias: { 'pptx-preview': rendererEntry },
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: 'NuwaxPptxPreview',
    target: ['es2020'],
    minify: true,
    write: false,
    metafile: true,
    legalComments: 'eof',
    define: { 'process.env.NODE_ENV': '"production"' },
    banner: {
      js: `/* Generated by npm run build:file-preview-pptx; pptx-preview@${rendererVersion} patched main, jszip@${zipVersion}. */`,
    },
  });
  const inputs = Object.keys(result.metafile.inputs);
  if (
    inputs.some((input) =>
      /(?:^|\/)(?:react|react-dom|umi|@umijs)(?:\/|$)/.test(input),
    )
  ) {
    throw new Error('静态 PPTX 预览依赖图不得包含 React 或 Umi。');
  }
  const resolvedInputs = new Set(
    inputs.map((input) => path.resolve(root, input)),
  );
  if (!resolvedInputs.has(rendererEntry) || !resolvedInputs.has(ownerEntry)) {
    throw new Error('静态 PPTX 资产缺少已补丁的渲染器或资源清理 helper。');
  }
  if (
    Object.values(result.metafile.outputs).some(
      (output) => output.imports.length,
    )
  ) {
    throw new Error('静态 PPTX 预览必须完整打包，不得依赖运行时模块加载。');
  }
  // esbuild 合并许可证时会为其空行加缩进；只去掉许可证注释的行尾空白。
  const output = result.outputFiles[0].text;
  const licenseStart = output.lastIndexOf('\n/*! Bundled license information:');
  const normalized =
    licenseStart < 0
      ? output
      : output.slice(0, licenseStart) +
        output.slice(licenseStart).replace(/[ \t]+$/gm, '');
  return { contents: Buffer.from(normalized), inputs, outputPath };
}

export async function runFilePreviewPptx({ check = false } = {}) {
  const result = await buildFilePreviewPptx();
  if (check) {
    let current;
    try {
      current = await fs.readFile(result.outputPath);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (!current || !current.equals(Buffer.from(result.contents))) {
      throw new Error(
        '静态 PPTX 资产与共享源码不一致，请运行 npm run build:file-preview-pptx 并提交生成文件。',
      );
    }
    console.log('静态 PPTX 资产检查通过（patched main，无 React/Umi）。');
  } else {
    await fs.mkdir(path.dirname(result.outputPath), { recursive: true });
    await fs.writeFile(result.outputPath, result.contents);
    console.log(
      `已生成静态 PPTX 资产（${result.contents.length} 字节，patched main，无 React/Umi）。`,
    );
  }
  return result;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check')) {
    console.error('用法：node scripts/build-file-preview-pptx.mjs [--check]');
    process.exitCode = 1;
  } else {
    try {
      await runFilePreviewPptx({ check: args.includes('--check') });
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}
