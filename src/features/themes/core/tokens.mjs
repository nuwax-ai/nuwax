export const defaultTokens = { light, dark };
export const tokenNames = Object.keys(light);
const kebab = (key) => key.replaceAll('.', '-');
export function tokenToCssVariables(tokens) {
  const result = {};
  result['--xagi-background-image'] = 'var(--nuwax-background-image, none)';
  for (const key of tokenNames)
    if (Object.hasOwn(tokens, key))
      for (const prefix of ['nuwax', 'xagi', 'v2'])
        result[`--${prefix}-${kebab(key)}`] = tokens[key];
  const aliases = {
    'bg-color': 'app.bg',
    'bg-secondary': 'surface.bg',
    'text-color': 'text.primary',
    'text-secondary': 'text.secondary',
    'border-color': 'border.default',
    'primary-color': 'primary',
    'primary-color-hover': 'primary.hover',
    'sidebar-bg': 'sidebar.bg',
    'card-bg': 'elevated.bg',
  };
  Object.assign(aliases, {
    'color-primary': 'primary',
    'color-primary-hover': 'primary.hover',
    'color-primary-active': 'primary.active',
    'color-primary-bg': 'selected.bg',
    'color-primary-border': 'focus.ring',
    'color-link': 'primary',
    'color-text': 'text.primary',
    'color-text-base': 'text.primary',
    'color-text-heading': 'text.primary',
    'color-text-secondary': 'text.secondary',
    'color-text-description': 'text.secondary',
    'color-text-tertiary': 'text.secondary',
    'color-text-quaternary': 'text.disabled',
    'color-text-disabled': 'text.disabled',
    'color-text-light-solid': 'text.inverse',
    'color-bg-base': 'app.bg',
    'color-bg-layout': 'surface.bg',
    'color-bg-container': 'elevated.bg',
    'color-bg-elevated': 'elevated.bg',
    'color-bg-container-disabled': 'surface.bg',
    'color-border': 'border.default',
    'color-border-secondary': 'border.default',
    'color-split': 'border.default',
    'color-fill': 'hover.bg',
    'color-fill-hover': 'hover.bg',
    'color-fill-secondary': 'hover.bg',
    'color-fill-tertiary': 'surface.bg',
    'color-fill-quaternary': 'surface.bg',
    'color-success': 'success',
    'color-warning': 'warning',
    'color-error': 'error',
    'color-info': 'info',
    'font-family': 'font.family',
    'font-family-code': 'font.code',
    'font-size': 'font.size',
    'border-radius': 'radius.medium',
    'border-radius-sm': 'radius.small',
    'border-radius-lg': 'radius.large',
  });
  // 新资料引导等组件沿用 Ant Design 默认前缀；与主站 xagi 前缀共用同套颜色。
  for (const prefix of ['xagi', 'v2', 'nuwax', 'ant'])
    for (const [alias, key] of Object.entries(aliases))
      if (Object.hasOwn(tokens, key))
        result[`--${prefix}-${alias}`] = tokens[key];
  const layoutAliases = {
    'bg-primary': 'surface.bg',
    'bg-secondary': 'sidebar.bg',
    'bg-container': 'app.bg',
    'bg-card': 'elevated.bg',
    'bg-input': 'input.bg',
    'text-primary': 'text.primary',
    'text-secondary': 'text.secondary',
    'text-tertiary': 'text.secondary',
    'text-disabled': 'text.disabled',
    'border-primary': 'border.strong',
    'border-secondary': 'border.default',
    'second-menu-text-color': 'text.primary',
    'second-menu-text-color-secondary': 'text.secondary',
    'second-menu-adaptive-text': 'text.primary',
    'second-menu-adaptive-text-secondary': 'text.secondary',
    'second-menu-adaptive-text-tertiary': 'text.disabled',
  };
  for (const [alias, key] of Object.entries(layoutAliases))
    if (Object.hasOwn(tokens, key))
      result[`--xagi-layout-${alias}`] = tokens[key];
  for (const [alias, key] of Object.entries({
    'item-hover-bg': 'hover.bg',
    'item-active-bg': 'selected.bg',
    'item-selected-bg': 'selected.bg',
    'second-item-active-bg': 'selected.bg',
    'row-hover-bg': 'hover.bg',
    'row-selected-bg': 'selected.bg',
  }))
    if (Object.hasOwn(tokens, key)) result[`--xagi-nav-${alias}`] = tokens[key];
  for (const [alias, key] of Object.entries({
    primary: 'primary',
    'primary-hover': 'primary.hover',
    'bg-layout': 'surface.bg',
    'bg-container': 'app.bg',
    'bg-elevated': 'elevated.bg',
    'bg-sider': 'sidebar.bg',
    'bg-section': 'surface.bg',
    'bg-hover': 'hover.bg',
    'bg-active': 'selected.bg',
    text: 'text.primary',
    'text-secondary': 'text.secondary',
    'text-tertiary': 'text.secondary',
    'text-disabled': 'text.disabled',
    border: 'border.default',
    'border-secondary': 'border.default',
    divider: 'border.default',
    // CardWrapper / AppCard 等旧卡片使用的设计变量名。
    'background-default': 'elevated.bg',
    'border-02': 'border.default',
    'border-primary': 'focus.ring',
    'font-primary': 'text.primary',
    'font-secondary': 'text.secondary',
    'font-tertiary': 'text.secondary',
  }))
    if (Object.hasOwn(tokens, key)) result[`--color-${alias}`] = tokens[key];
  return result;
}
